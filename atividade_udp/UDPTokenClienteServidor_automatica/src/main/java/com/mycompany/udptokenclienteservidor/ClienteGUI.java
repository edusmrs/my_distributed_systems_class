    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        String nome = txtNome.getText().trim();
        if (nome.isEmpty()) {
            JOptionPane.showMessageDialog(this, "preencha o nome");
            return;
        }

        String resposta = enviarRequisicaoSimples("CADASTRO;" + nome);
        
        if (resposta != null) {
            String[] partes = resposta.split(";");
            if (partes[0].equals("OK_CADASTRO")) {
                JOptionPane.showMessageDialog(this, "conta criada. \nEmail: " + partes[1]);
                txtEmailBusca.setText(partes[1]); 
                txtNome.setText("");
            } else {
                JOptionPane.showMessageDialog(this, partes[1], "Erro", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "erro de rede no cadastro.", "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCadastrarActionPerformed

