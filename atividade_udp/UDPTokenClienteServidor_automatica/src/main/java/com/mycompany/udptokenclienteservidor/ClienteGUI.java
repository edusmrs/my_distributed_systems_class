    private void btnLogarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLogarActionPerformed
       String email = txtEmailBusca.getText().trim();
        if (email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha o email para logar");
            return;
        }
        
        if (socketCliente == null || socketCliente.isClosed()) {
            iniciarConexao();
        }

        String comando = "LOGIN;" + email;
        DatagramPacket pacoteEnvio = ComunicadorUDP.montaMensagem(comando, "localhost", 1234);
        ComunicadorUDP.enviaMensagem(socketCliente, pacoteEnvio);
    }//GEN-LAST:event_btnLogarActionPerformed

