   private String enviarRequisicaoSimples(String comando) {
        try (DatagramSocket socketTemp = new DatagramSocket()) {
            socketTemp.setSoTimeout(3000);
            DatagramPacket pacoteEnvio = ComunicadorUDP.montaMensagem(comando, "localhost", 1234);
            ComunicadorUDP.enviaMensagem(socketTemp, pacoteEnvio);
            DatagramPacket pacoteResposta = ComunicadorUDP.recebeMensagem(socketTemp);
            if (pacoteResposta != null) return new String(pacoteResposta.getData()).trim();
        } catch (Exception ex) {
            ex.printStackTrace();
        }
        return null; 
    }
   
   private void iniciarConexao() {
        try {
            socketCliente = new DatagramSocket();
            escutando = true;
            
            // escutando o servidor
            Thread ouvinte = new Thread(() -> {
                while (escutando) {
                    DatagramPacket pacote = ComunicadorUDP.recebeMensagem(socketCliente);
                    if (pacote != null) {
                        String mensagemRecebida = new String(pacote.getData()).trim();
                        processarMensagemDoServidor(mensagemRecebida);
                    }
                }
            });
            ouvinte.setDaemon(true);
            ouvinte.start();
            
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "erro ao abrir porta UDP no cliente.");
        }
    }
   
    private void processarMensagemDoServidor(String mensagem) {
        javax.swing.SwingUtilities.invokeLater(() -> {
            String[] partes = mensagem.split(";");
            
            if (partes[0].equals("OK_LOGIN")) {
                lblResultadoToken.setText("aguardando tokens...");
                JOptionPane.showMessageDialog(this, partes[1]);
            } else if (partes[0].equals("ERRO")) {
                JOptionPane.showMessageDialog(this, partes[1], "Erro", JOptionPane.ERROR_MESSAGE);
            } else if (partes[0].equals("NOVO_TOKEN")) {
                lblResultadoToken.setText("Token Atual: " + partes[1]);
            }
        });
    }
    
    

