    private void btnPedirTokenActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPedirTokenActionPerformed
       String email = txtEmailToken.getText().trim();
        if (email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha o email para buscar o token!");
            return;
        }
        
        String resposta = enviarRequisicaoUDP("SOLICITAR_TOKEN;" + email);
        if (resposta != null) {
            String[] partes = resposta.split(";");
            if (partes.length >= 2 && partes[0].equals("TOKEN")) {
                lblResultadoToken.setText("Token: " + partes[1]);
            } else {
                lblResultadoToken.setText("Token: Não encontrado");
                JOptionPane.showMessageDialog(this, partes.length >= 2 ? partes[1] : "Resposta inválida", "Aviso", JOptionPane.WARNING_MESSAGE);
            }
        } else {
            lblResultadoToken.setText("Token: Falha na conexão");
            JOptionPane.showMessageDialog(this, "Erro de rede (Timeout).", "Erro UDP", JOptionPane.ERROR_MESSAGE);
        } 
    }//GEN-LAST:event_btnPedirTokenActionPerformed

