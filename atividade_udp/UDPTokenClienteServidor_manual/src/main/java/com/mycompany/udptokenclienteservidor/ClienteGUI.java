    private String enviarRequisicaoUDP(String comando) {
        try (DatagramSocket socketCliente = new DatagramSocket()) {
            socketCliente.setSoTimeout(3000); // 3 segundos de timeout
            
            DatagramPacket pacoteEnvio = ComunicadorUDP.montaMensagem(comando, "localhost", 1234);
            ComunicadorUDP.enviaMensagem(socketCliente, pacoteEnvio);
            
            DatagramPacket pacoteResposta = ComunicadorUDP.recebeMensagem(socketCliente);
            if (pacoteResposta != null) {
                return new String(pacoteResposta.getData()).trim();
            }
        } catch (Exception ex) {
            logger.log(java.util.logging.Level.SEVERE, "Erro na comunicação UDP", ex);
        }
        return null; 
    }

