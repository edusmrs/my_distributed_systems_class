    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        String nome = txtNome.getText().trim();
        
        if (nome.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha o nome para gerar o cadastro!");
            return;
        }
        
        // Se o nome tiver espaços repetidos, o trim() cuida das pontas, mas é bom avisar
        if (!nome.contains(" ")) {
            int resposta = JOptionPane.showConfirmDialog(this, 
                "Você inseriu apenas um nome. O email ficará sem sobrenome. Deseja continuar?", 
                "Aviso", JOptionPane.YES_NO_OPTION);
            if (resposta != JOptionPane.YES_OPTION) return;
        }

        String respostaServidor = enviarRequisicaoUDP("CADASTRO;" + nome);
        
        if (respostaServidor != null) {
            String[] partes = respostaServidor.split(";");
            if (partes[0].equals("OK")) {
                String emailRecebido = partes[1];
                
                JOptionPane.showMessageDialog(this, "Cadastro realizado!\nSeu email institucional é:\n" + emailRecebido);
                
                txtEmailToken.setText(emailRecebido); 
                txtNome.setText(""); 
                
            } else {
                JOptionPane.showMessageDialog(this, partes[1], "Erro no Cadastro", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Erro de rede (Timeout). Servidor não respondeu.", "Erro", JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_btnCadastrarActionPerformed

